@dataclass(frozen=True, slots=True)
class FeatureSchemaMetadata:
    """Schema descriptor containing feature metadata and constraints."""

    version: str
    feature_count: int
    features: list[str]
    metadata_columns: list[str]
    dtype: str = "float32"
    nan_policy: str = "reject_or_zero"
    scaling_policy: str = "standard_scaler"


def get_schema_metadata() -> FeatureSchemaMetadata:
    """Return the immutable schema metadata."""
    return FeatureSchemaMetadata(
        version=SCHEMA_VERSION,
        feature_count=CANONICAL_FEATURE_DIM,
        features=list(CANONICAL_FEATURES),
        metadata_columns=list(METADATA_COLUMNS),
    )


def align_dataframe_to_schema(
    df: pd.DataFrame,
    fill_missing_features: bool = True,
    default_fill_value: float = 0.0,
) -> pd.DataFrame:
    """Standardize an input DataFrame (e.g. parsed from CSV) to the canonical schema.

    1. Applies column aliases from CIC_COLUMN_ALIASES.
    2. Ensures all CANONICAL_FEATURES are present in exact canonical order.
    3. Converts canonical features to np.float32.
    4. Retains recognized metadata columns (e.g. timestamp, attack label).

    Args:
        df: Input DataFrame.
        fill_missing_features: If True, missing canonical features are populated
            with default_fill_value. If False, raises KeyError.
        default_fill_value: Value used to fill missing feature columns.

    Returns:
        Standardized DataFrame with canonical features in correct order followed
        by available metadata columns.
    """
    df = df.copy()

    # Normalize column names: strip whitespace and apply alias mapping
    renamed = {c: CIC_COLUMN_ALIASES.get(c.strip(), c.strip()) for c in df.columns}
    df.rename(columns=renamed, inplace=True)

    # Derive missing statistical variance and rate features if primaries exist
    if "fwd_pkt_len_var" not in df.columns and "fwd_pkt_len_std" in df.columns:
        df["fwd_pkt_len_var"] = pd.to_numeric(df["fwd_pkt_len_std"], errors="coerce").fillna(0.0) ** 2
    if "bwd_pkt_len_var" not in df.columns and "bwd_pkt_len_std" in df.columns:
        df["bwd_pkt_len_var"] = pd.to_numeric(df["bwd_pkt_len_std"], errors="coerce").fillna(0.0) ** 2
    if "pkt_len_var" not in df.columns and "pkt_len_std" in df.columns:
        df["pkt_len_var"] = pd.to_numeric(df["pkt_len_std"], errors="coerce").fillna(0.0) ** 2
    if "flow_iat_total" not in df.columns:
        if "fwd_iat_total" in df.columns and "bwd_iat_total" in df.columns:
            df["flow_iat_total"] = (
                pd.to_numeric(df["fwd_iat_total"], errors="coerce").fillna(0.0)
                + pd.to_numeric(df["bwd_iat_total"], errors="coerce").fillna(0.0)
            )
        elif "flow_duration_us" in df.columns:
            df["flow_iat_total"] = pd.to_numeric(df["flow_duration_us"], errors="coerce").fillna(0.0)
    if "fwd_bytes_per_s" not in df.columns and "tot_fwd_bytes" in df.columns and "flow_duration_us" in df.columns:
        dur_s = np.maximum(pd.to_numeric(df["flow_duration_us"], errors="coerce").fillna(0.0).to_numpy() / 1e6, 1e-6)
        df["fwd_bytes_per_s"] = pd.to_numeric(df["tot_fwd_bytes"], errors="coerce").fillna(0.0).to_numpy() / dur_s
    if "bwd_bytes_per_s" not in df.columns and "tot_bwd_bytes" in df.columns and "flow_duration_us" in df.columns:
        dur_s = np.maximum(pd.to_numeric(df["flow_duration_us"], errors="coerce").fillna(0.0).to_numpy() / 1e6, 1e-6)
        df["bwd_bytes_per_s"] = pd.to_numeric(df["tot_bwd_bytes"], errors="coerce").fillna(0.0).to_numpy() / dur_s

    missing = [f for f in CANONICAL_FEATURES if f not in df.columns]
    if missing:
        if not fill_missing_features:
            raise KeyError(f"Input DataFrame is missing required canonical features: {missing}")
        for f in missing:
            df[f] = default_fill_value

    # Cast all canonical features to float32
    for f in CANONICAL_FEATURES:
        df[f] = pd.to_numeric(df[f], errors="coerce").fillna(default_fill_value).astype(np.float32)

    # Reorder columns: canonical features first, then available metadata
    retained_meta = [c for c in METADATA_COLUMNS if c in df.columns]
    other_cols = [c for c in df.columns if c not in CANONICAL_FEATURES and c not in retained_meta]
    ordered_cols = list(CANONICAL_FEATURES) + retained_meta + other_cols
    return df[ordered_cols]


def validate_feature_vector(
    vector: np.ndarray,
    feature_names: list[str] | None = None,
) -> bool:
    """Validate that a 1D feature array conforms to the canonical schema."""
    if vector.ndim != 1:
        raise ValueError(f"Feature vector must be 1D, got shape {vector.shape}")
    if len(vector) != CANONICAL_FEATURE_DIM:
        raise ValueError(
            f"Feature vector length {len(vector)} does not match canonical dimension {CANONICAL_FEATURE_DIM}"
        )
    if not np.all(np.isfinite(vector)):
        raise ValueError("Feature vector contains NaN or Infinite values")
    if feature_names is not None and tuple(feature_names) != CANONICAL_FEATURES:
        raise ValueError("Feature vector names do not strictly match CANONICAL_FEATURES ordering")
    return True


def export_schema_json(dest_path: Path | str) -> Path:
    """Export schema metadata as a JSON file."""
    dest = Path(dest_path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    meta = get_schema_metadata()
    with open(dest, "w", encoding="utf-8") as f:
        json.dump(asdict(meta), f, indent=2)
    return dest
